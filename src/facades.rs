//! Laravel's facade aliases, read from the installed framework and written as
//! `class_alias` calls that Intelephense indexes.
//!
//! Laravel registers `Route`, `Auth`, `DB`, … at runtime with
//! `Illuminate\Foundation\AliasLoader`, which calls `class_alias()`. PHP code in
//! the global namespace may therefore use the short names without a `use`
//! statement (this is what `routes/api.php` files do). Intelephense does not
//! run the application, so without a declaration it reports `Undefined type
//! 'Route'` (P1009). Intelephense does understand `class_alias()`, so a small
//! generated file with one call per alias is enough.

use std::collections::BTreeMap;

/// The conventional generated file. Laravel projects ignore it in `.gitignore`.
pub const HELPER_FILE: &str = "_ide_helper.php";

/// Marks the file as ours, so a later version may update it and a user's own
/// `_ide_helper.php` (from laravel-ide-helper) is never overwritten.
pub const MARKER: &str = "@generated by konakona.laravel-facades";

/// The framework file that lists the default aliases.
pub const FACADE_SOURCE: &str = "vendor/laravel/framework/src/Illuminate/Support/Facades/Facade.php";

/// Where applications add aliases of their own (Laravel 10 and earlier).
pub const CONFIG_SOURCE: &str = "config/app.php";

/// A target class for an alias, without a leading backslash.
pub type Aliases = BTreeMap<String, String>;

/// The file to write, or a reason not to touch the project.
#[derive(Debug, PartialEq, Eq)]
pub enum Plan {
    Write(String),
    UpToDate,
    Foreign,
}

/// The aliases Laravel registers by default, from `Facade::defaultAliases()`.
pub fn default_aliases(source: &str) -> Aliases {
    let uses = parse_use_map(source);
    let Some(body) = function_array(source, "defaultAliases") else { return Aliases::new() };
    let mut out = Aliases::new();
    for (alias, value) in parse_string_map(body) {
        if let Some(target) = resolve(&value, "Illuminate\\Support\\Facades", &uses) {
            out.insert(alias, target);
        }
    }
    out
}

/// Aliases an application adds in `config/app.php` (`'aliases' => [...]`).
pub fn config_aliases(source: &str) -> Aliases {
    let uses = parse_use_map(source);
    let Some(at) = source.find("'aliases'") else { return Aliases::new() };
    let Some(open) = source[at..].find('[').map(|i| at + i) else { return Aliases::new() };
    let Some(body) = bracket_body(source, open) else { return Aliases::new() };
    // Laravel 11+ writes `Facade::defaultAliases()->merge([...])->toArray()`;
    // its defaults come from the framework file, not from this expression.
    if body.contains("defaultAliases()") {
        return Aliases::new();
    }
    let mut out = Aliases::new();
    for (alias, value) in parse_string_map(body) {
        if let Some(target) = resolve(&value, "", &uses) {
            out.insert(alias, target);
        }
    }
    out
}

/// The generated stub for `aliases`.
pub fn stub(aliases: &Aliases) -> String {
    let mut out = format!(
        "<?php\n\n// {MARKER} {} — do not edit.\n// Laravel facade aliases for Intelephense; never included at runtime.\n// Delete this file to have the plugin create it again.\n\n",
        env!("CARGO_PKG_VERSION")
    );
    for (alias, target) in aliases {
        out.push_str(&format!("class_alias(\\{target}::class, '{alias}');\n"));
    }
    out
}

/// What to do with the current `_ide_helper.php` contents and the aliases.
pub fn plan(existing: Option<&str>, aliases: &Aliases) -> Plan {
    let content = stub(aliases);
    let Some(existing) = existing else { return Plan::Write(content) };
    if existing.contains(MARKER) {
        return if existing == content { Plan::UpToDate } else { Plan::Write(content) };
    }
    if aliases.iter().all(|(alias, _)| declares_alias(existing, alias)) {
        Plan::UpToDate
    } else {
        Plan::Foreign
    }
}

/// Whether `source` already declares `alias` as a global class or class_alias.
pub fn declares_alias(source: &str, alias: &str) -> bool {
    let quoted = [format!("'{alias}'"), format!("\"{alias}\"")];
    source.lines().map(str::trim).any(|line| {
        let class = line.strip_prefix("class ").is_some_and(|rest| {
            rest.strip_prefix(alias).is_some_and(|tail| {
                tail.starts_with(' ')
                    || tail.starts_with('{')
                    || tail.starts_with(':')
                    || tail.starts_with(" extends")
                    || tail.starts_with(" implements")
            })
        });
        let aliased = line.contains("class_alias(") && quoted.iter().any(|q| line.contains(q.as_str()));
        class || aliased
    })
}

/// `(alias, right-hand side)` of each `'alias' => value` line in an array body.
fn parse_string_map(body: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for line in body.lines() {
        let line = line.trim();
        if line.is_empty()
            || line.starts_with("//")
            || line.starts_with("/*")
            || line.starts_with('*')
            || line.starts_with("#[")
        {
            continue;
        }
        let Some((left, right)) = line.split_once("=>") else { continue };
        let Some(alias) = unquote(left.trim()) else { continue };
        // A value ends at the comma before the next key; the entries here are
        // simple (`Foo::class`, `'Fully\\Qualified'`), so the last comma works.
        let right = right.trim().trim_end_matches(',').trim();
        if right.is_empty() || right.contains('(') || right.contains('[') {
            continue;
        }
        out.push((alias, right.to_owned()));
    }
    out
}

/// A PHP single- or double-quoted string, without the quotes.
fn unquote(text: &str) -> Option<String> {
    let text = text.trim();
    let quote = text.chars().next()?;
    if !matches!(quote, '\'' | '"') || !text.ends_with(quote) || text.len() < 2 {
        return None;
    }
    Some(text[1..text.len() - 1].to_owned())
}

/// Resolve the right-hand side of an alias entry to a fully-qualified class.
fn resolve(value: &str, namespace: &str, uses: &BTreeMap<String, String>) -> Option<String> {
    let value = value.trim();
    if let Some(class) = unquote(value) {
        let class = class.trim_start_matches('\\');
        return valid_class(class).then(|| class.to_owned());
    }
    let name = value.strip_suffix("::class")?.trim();
    if name.is_empty() || name.contains([' ', '\'', '"', '$', '(']) {
        return None;
    }
    let name = name.trim_start_matches('\\');
    let (first, rest) = match name.split_once('\\') {
        Some((first, rest)) => (first, Some(rest)),
        None => (name, None),
    };
    let base = if let Some(target) = uses.get(first) {
        target.clone()
    } else if namespace.is_empty() {
        first.to_owned()
    } else {
        // A name in the file's own namespace, like `Route` in
        // `Illuminate\Support\Facades\Facade::defaultAliases()`.
        format!("{namespace}\\{first}")
    };
    let target = match rest {
        Some(rest) => format!("{base}\\{rest}"),
        None => base,
    };
    valid_class(&target).then_some(target)
}

fn valid_class(class: &str) -> bool {
    !class.is_empty()
        && class.split('\\').all(|part| {
            let mut chars = part.chars();
            chars.next().is_some_and(|c| c == '_' || c.is_ascii_alphabetic())
                && chars.all(|c| c == '_' || c.is_ascii_alphanumeric())
        })
}

/// `use` imports, short name → fully-qualified name.
fn parse_use_map(source: &str) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    for line in source.lines() {
        let line = line.trim();
        let Some(rest) = line.strip_prefix("use ") else { continue };
        let rest = rest.trim_end_matches(';').trim();
        if rest.starts_with("function ") || rest.starts_with("const ") || rest.is_empty() {
            continue;
        }
        if let Some((prefix, inner)) = rest.split_once('{') {
            // use Illuminate\Support\{Arr, Str};
            let prefix = prefix.trim().trim_end_matches('\\');
            for part in inner.trim_end_matches('}').split(',') {
                let part = part.trim();
                if part.is_empty() {
                    continue;
                }
                let (name, alias) = split_alias(part);
                let short = alias.unwrap_or_else(|| short_name(name));
                out.insert(short.to_owned(), format!("{prefix}\\{}", name.trim_start_matches('\\')));
            }
            continue;
        }
        let (name, alias) = split_alias(rest);
        let short = alias.unwrap_or_else(|| short_name(name));
        out.insert(short.to_owned(), name.trim_start_matches('\\').to_owned());
    }
    out
}

fn split_alias(part: &str) -> (&str, Option<&str>) {
    match part.split_once(" as ") {
        Some((name, alias)) => (name.trim(), Some(alias.trim())),
        None => (part.trim(), None),
    }
}

fn short_name(name: &str) -> &str {
    name.rsplit('\\').next().unwrap_or(name)
}

/// The inside of the array `function_name` returns.
fn function_array<'a>(source: &'a str, function_name: &str) -> Option<&'a str> {
    let at = source.find(&format!("function {function_name}"))?;
    let open = source[at..].find('[').map(|i| at + i)?;
    bracket_body(source, open)
}

/// The text between the `[` at `open` and its matching `]`.
fn bracket_body(source: &str, open: usize) -> Option<&str> {
    let bytes = source.as_bytes();
    if bytes.get(open) != Some(&b'[') {
        return None;
    }
    let mut depth = 0usize;
    let mut quote = None;
    let mut i = open;
    while i < bytes.len() {
        let c = bytes[i] as char;
        if let Some(q) = quote {
            if c == q && bytes.get(i.wrapping_sub(1)) != Some(&b'\\') {
                quote = None;
            }
        } else {
            match c {
                '\'' | '"' => quote = Some(c),
                '[' => depth += 1,
                ']' => {
                    depth -= 1;
                    if depth == 0 {
                        return Some(&source[open + 1..i]);
                    }
                }
                _ => {}
            }
        }
        i += 1;
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    const FACADE: &str = r#"<?php

namespace Illuminate\Support\Facades;

use Closure;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Arr;
use Illuminate\Support\Str;

abstract class Facade
{
    public static function defaultAliases()
    {
        return new Collection([
            'App' => App::class,
            'Arr' => Arr::class,
            'Eloquent' => Model::class,
            'Route' => Route::class,
            'Str' => Str::class,
        ]);
    }
}
"#;

    #[test]
    fn reads_the_default_aliases_and_resolves_imports_and_the_facade_namespace() {
        let aliases = default_aliases(FACADE);
        assert_eq!(aliases["Route"], "Illuminate\\Support\\Facades\\Route");
        assert_eq!(aliases["App"], "Illuminate\\Support\\Facades\\App");
        assert_eq!(aliases["Arr"], "Illuminate\\Support\\Arr");
        assert_eq!(aliases["Eloquent"], "Illuminate\\Database\\Eloquent\\Model");
        assert_eq!(aliases["Str"], "Illuminate\\Support\\Str");
        assert_eq!(aliases.len(), 5);
    }

    #[test]
    fn reads_qualified_and_quoted_values() {
        let source = r#"<?php
use Illuminate\Support\Facades\Route;

return [
    'aliases' => [
        'Router' => Route::class,
        'Legacy' => 'Illuminate\Support\Facades\Legacy',
        'Broken' => SomeFactory::make(),
    ],
];
"#;
        let aliases = config_aliases(source);
        assert_eq!(aliases["Router"], "Illuminate\\Support\\Facades\\Route");
        assert_eq!(aliases["Legacy"], "Illuminate\\Support\\Facades\\Legacy");
        assert!(!aliases.contains_key("Broken"));
    }

    #[test]
    fn laravel_11_config_aliases_are_left_to_the_framework_file() {
        let source = r#"<?php
return [
    'aliases' => Facade::defaultAliases()->merge([])->toArray(),
];
"#;
        assert!(config_aliases(source).is_empty());
    }

    #[test]
    fn writes_one_class_alias_per_line() {
        let aliases = default_aliases(FACADE);
        let text = stub(&aliases);
        assert!(text.starts_with("<?php"));
        assert!(text.contains(MARKER));
        assert!(text.contains("class_alias(\\Illuminate\\Support\\Facades\\Route::class, 'Route');"));
        assert!(text.contains("class_alias(\\Illuminate\\Database\\Eloquent\\Model::class, 'Eloquent');"));
    }

    #[test]
    fn leaves_an_existing_file_of_the_user_alone() {
        let aliases = default_aliases(FACADE);
        assert_eq!(plan(Some("<?php\n// laravel-ide-helper\n"), &aliases), Plan::Foreign);
        assert_eq!(plan(Some("<?php\nclass Route {}\n"), &aliases), Plan::Foreign);
        assert!(matches!(
            plan(Some("<?php\n// @generated by konakona.laravel-facades 0.0.1\n"), &aliases),
            Plan::Write(_)
        ));
        assert!(matches!(plan(None, &aliases), Plan::Write(_)));
    }

    #[test]
    fn the_generated_file_is_not_rewritten_while_it_is_current() {
        let aliases = default_aliases(FACADE);
        let text = stub(&aliases);
        assert_eq!(plan(Some(&text), &aliases), Plan::UpToDate);
        assert!(matches!(plan(Some("<?php\n// @generated by konakona.laravel-facades 0.0.1\n"), &aliases), Plan::Write(_)));
    }

    #[test]
    fn recognizes_classes_and_class_aliases_a_helper_file_already_declares() {
        assert!(declares_alias("<?php\nclass Route extends Foo {}\n", "Route"));
        assert!(declares_alias("<?php\nclass_alias(\\Foo::class, 'Route');\n", "Route"));
        assert!(!declares_alias("<?php\nclass RouteX {}\n", "Route"));
    }

    #[test]
    fn ignores_comments_and_unquoted_keys() {
        let source = r#"<?php
return [
    'aliases' => [
        // 'Comment' => App::class,
        'Route' => Route::class,
        $dynamic => App::class,
    ],
];
"#;
        let aliases = config_aliases(source);
        assert!(aliases.contains_key("Route"));
        assert!(!aliases.contains_key("Comment"));
    }
}


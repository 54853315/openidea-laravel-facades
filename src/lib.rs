//! Laravel facade aliases for Intelephense.
//!
//! Laravel's `routes/*.php` files use `Route` without a `use` statement: the
//! alias is registered at runtime by `AliasLoader`, which calls
//! `class_alias()`. Intelephense never runs the application, so it reports
//! `Undefined type 'Route'` (`P1009`). It does understand `class_alias()`,
//! so this plugin writes Laravel's default aliases to the conventional
//! `_ide_helper.php` file, which Intelephense indexes with the project.

mod facades;

use openidea_plugin::{
    Context, Error, Event, EventKind, Invocation, LogLevel, NotificationLevel, Plugin, Project, host,
    register_plugin,
};

const AUTO_GENERATE: &str = "autoGenerate";

#[derive(Default)]
struct LaravelFacades {
    /// Projects that already showed the "grant a process capability" warning.
    warned: std::collections::BTreeSet<String>,
}

impl Plugin for LaravelFacades {
    fn activate(&mut self, _ctx: &Context) -> Result<(), Error> {
        host::subscribe(EventKind::FileOpened)?;
        host::subscribe(EventKind::FileSaved)?;
        if auto_generate()
            && let Ok(projects) = host::projects()
        {
            for project in projects {
                self.ensure_project(&project);
            }
        }
        Ok(())
    }

    fn run_command(&mut self, id: &str, ctx: &Invocation, _arg: Option<&str>) -> Result<Option<String>, Error> {
        if id != "generate" {
            return Err(Error::NotFound(format!("command {id}")));
        }
        let project = ctx.project().ok_or("No project is open.")?;
        match ensure(&project) {
            Ok(Outcome::Written) => Ok(Some("Laravel facade stubs written to _ide_helper.php.".into())),
            Ok(Outcome::UpToDate) => Ok(Some("_ide_helper.php already declares Laravel's facade aliases.".into())),
            Ok(Outcome::Foreign) => Ok(Some(
                "_ide_helper.php already exists and was not generated by this plugin; left untouched.".into(),
            )),
            Ok(Outcome::NotLaravel) => Ok(Some("This project is not a Laravel application.".into())),
            Ok(Outcome::NoAliases) => Ok(Some(
                "No facade aliases found. Run `composer install` so vendor/laravel/framework is present.".into(),
            )),
            Err(e) => Err(e),
        }
    }

    fn handle_events(&mut self, events: &[Event], ctx: &Invocation) {
        let Some(project) = ctx.project() else { return };
        for event in events {
            match event {
                Event::FileOpened(path) if path.ends_with(".php") => {
                    if !auto_generate() {
                        continue;
                    }
                    self.ensure_project(&project);
                }
                Event::FileSaved(path)
                    if path.ends_with("composer.json") || path.ends_with("composer.lock") =>
                {
                    if !auto_generate() {
                        continue;
                    }
                    if let Err(e) = ensure(&project) {
                        host::log(LogLevel::Warn, &format!("laravel-facades: {e}"));
                    }
                }
                _ => {}
            }
        }
    }
}

fn auto_generate() -> bool {
    host::setting_bool(AUTO_GENERATE).unwrap_or(true)
}

impl LaravelFacades {
    fn ensure_project(&mut self, project: &Project) {
        let root = project.root().unwrap_or_default();
        match ensure(project) {
            Ok(Outcome::Written) => {
                host::log(LogLevel::Info, "laravel-facades: wrote _ide_helper.php");
            }
            Ok(_) => {}
            Err(Error::Denied(_)) => {
                if self.warned.insert(root) {
                    host::notify(
                        NotificationLevel::Warning,
                        "Laravel Facades",
                        "Allow “Run tee” or “Run php” for Laravel Facades in Settings › Plugins, then run “Laravel: Generate Facade Stubs”.",
                    );
                }
            }
            Err(e) => host::log(LogLevel::Warn, &format!("laravel-facades: {e}")),
        }
    }
}

#[derive(Debug, PartialEq, Eq)]
enum Outcome {
    Written,
    UpToDate,
    Foreign,
    NotLaravel,
    NoAliases,
}

/// Ensure the project has a `_ide_helper.php` with Laravel's facade aliases.
fn ensure(project: &Project) -> Result<Outcome, Error> {
    if !is_laravel(project)? {
        return Ok(Outcome::NotLaravel);
    }

    let Some(source) = read_optional(project, facades::FACADE_SOURCE)? else {
        return Ok(Outcome::NoAliases);
    };
    let mut aliases = facades::default_aliases(&source);
    if let Some(source) = read_optional(project, facades::CONFIG_SOURCE)? {
        for (alias, target) in facades::config_aliases(&source) {
            aliases.insert(alias, target);
        }
    }
    if aliases.is_empty() {
        return Ok(Outcome::NoAliases);
    }

    let existing = read_optional(project, facades::HELPER_FILE)?;
    match facades::plan(existing.as_deref(), &aliases) {
        facades::Plan::Write(content) => {
            write_file(project, facades::HELPER_FILE, &content)?;
            Ok(Outcome::Written)
        }
        facades::Plan::UpToDate => Ok(Outcome::UpToDate),
        facades::Plan::Foreign => Ok(Outcome::Foreign),
    }
}

/// A file the plugin may need but that may not exist.
///
/// OpenIDEA 0.1.38 reports a missing file as `Invalid("<path>: no such file")`
/// rather than `NotFound`, so both forms mean "absent" here. Anything else
/// (an outside-root path, a directory, an unreadable file) stays an error.
fn read_optional(project: &Project, path: &str) -> Result<Option<String>, Error> {
    match project.read_file(path) {
        Ok(text) => Ok(Some(text)),
        Err(e) if is_missing(&e) => Ok(None),
        Err(e) => Err(e),
    }
}

fn is_missing(error: &Error) -> bool {
    match error {
        Error::NotFound(_) => true,
        Error::Invalid(message) => message.contains("no such file") || message.contains("not found"),
        _ => false,
    }
}

/// A Laravel application: it has an `artisan` file or requires the framework.
fn is_laravel(project: &Project) -> Result<bool, Error> {
    if read_optional(project, "artisan")?.is_some() {
        return Ok(true);
    }
    match read_optional(project, "composer.json")? {
        Some(composer) => Ok(composer.contains("\"laravel/framework\"")),
        None => Ok(false),
    }
}

/// Write the generated file. `tee` is the simplest way on macOS and Linux;
/// `php` works on Windows and where `tee` is not installed. Both are optional
/// capabilities, so a refused one falls back to the other.
fn write_file(project: &Project, relative: &str, content: &str) -> Result<(), Error> {
    let root = project.root()?;
    let path = format!("{}/{}", root.trim_end_matches('/'), relative);
    match host::run_process("tee", &[path], Some(content)) {
        Ok(out) if out.status == Some(0) => return Ok(()),
        Ok(_) => {}
        Err(Error::Denied(_)) | Err(Error::NotFound(_)) => {}
        Err(e) => return Err(e),
    }

    let args = vec![
        "-r".to_string(),
        "file_put_contents($argv[1], stream_get_contents(STDIN));".to_string(),
        "--".to_string(),
        relative.to_string(),
    ];
    match host::run_process("php", &args, Some(content)) {
        Ok(out) if out.status == Some(0) => Ok(()),
        Ok(out) => Err(Error::Invalid(format!("Could not write {relative}: {}", out.stderr.trim()))),
        Err(Error::Denied(_)) => Err(Error::Denied("process:tee or process:php".into())),
        Err(e) => Err(e),
    }
}

register_plugin!(LaravelFacades);

#[cfg(test)]
mod tests {
    use super::*;
    use openidea_plugin::mock::MockHost;
    use openidea_plugin::ProcessOutput;

    const FACADE: &str = r#"<?php

namespace Illuminate\Support\Facades;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Arr;
use Illuminate\Support\Str;

abstract class Facade
{
    public static function defaultAliases()
    {
        return new Collection([
            'Arr' => Arr::class,
            'Eloquent' => Model::class,
            'Route' => Route::class,
            'Str' => Str::class,
        ]);
    }
}
"#;

    fn project(host: &MockHost) {
        host.set_project_root(Some("/p"));
        host.add_file("artisan", "");
        host.add_file("composer.json", r#"{"require":{"laravel/framework":"^13.0"}}"#);
        host.add_file("vendor/laravel/framework/src/Illuminate/Support/Facades/Facade.php", FACADE);
    }

    fn tee(host: &MockHost, written: std::rc::Rc<std::cell::RefCell<Option<String>>>) {
        host.on_process("tee", move |_args, stdin| {
            *written.borrow_mut() = stdin.map(str::to_owned);
            Ok(ProcessOutput { status: Some(0), stdout: String::new(), stderr: String::new() })
        });
    }

    #[test]
    fn opening_a_php_file_writes_the_aliases() {
        let host = MockHost::install().with_capabilities(&["project.read", "events", "process:tee"]);
        project(&host);
        let written = std::rc::Rc::new(std::cell::RefCell::new(None));
        tee(&host, written.clone());

        let mut plugin = LaravelFacades::default();
        plugin.handle_events(&[Event::FileOpened("/p/routes/api.php".into())], &host.invocation());

        let text = written.borrow().clone().expect("tee received the stub");
        assert!(text.contains("class_alias(\\Illuminate\\Support\\Facades\\Route::class, 'Route');"));
        assert!(text.contains("class_alias(\\Illuminate\\Database\\Eloquent\\Model::class, 'Eloquent');"));
        assert!(text.contains(facades::MARKER));
        assert_eq!(host.process_runs()[0].program, "tee");
    }

    #[test]
    fn writes_the_aliases_when_the_workbench_starts() {
        let host = MockHost::install().with_capabilities(&["project.read", "events", "process:tee"]);
        project(&host);
        let written = std::rc::Rc::new(std::cell::RefCell::new(None));
        tee(&host, written.clone());

        let mut plugin = LaravelFacades::default();
        plugin.activate(&host.context("konakona.laravel-facades")).unwrap();
        assert!(host.subscriptions().contains(&EventKind::FileOpened));
        assert!(host.subscriptions().contains(&EventKind::FileSaved));
        assert!(written.borrow().as_deref().is_some_and(|t| t.contains("'Route'")));
    }

    #[test]
    fn automatic_generation_can_be_turned_off() {
        let host = MockHost::install().with_capabilities(&["project.read", "events", "process:tee"]);
        project(&host);
        host.set_setting("autoGenerate", "false");

        let mut plugin = LaravelFacades::default();
        plugin.activate(&host.context("konakona.laravel-facades")).unwrap();
        plugin.handle_events(&[Event::FileOpened("/p/routes/api.php".into())], &host.invocation());
        assert!(host.process_runs().is_empty());
    }

    #[test]
    fn falls_back_to_php_when_tee_is_refused() {
        let host = MockHost::install().with_capabilities(&["project.read", "events", "process:php"]);
        project(&host);
        let written = std::rc::Rc::new(std::cell::RefCell::new(None));
        let captured = written.clone();
        host.on_process("php", move |args, stdin| {
            assert_eq!(args[0], "-r");
            assert_eq!(args[2], "--");
            assert_eq!(args[3], "_ide_helper.php");
            *captured.borrow_mut() = stdin.map(str::to_owned);
            Ok(ProcessOutput { status: Some(0), stdout: String::new(), stderr: String::new() })
        });

        let mut plugin = LaravelFacades::default();
        plugin.handle_events(&[Event::FileOpened("/p/routes/api.php".into())], &host.invocation());
        assert!(written.borrow().as_deref().is_some_and(|t| t.contains("'Route'")));
        assert_eq!(host.process_runs()[0].program, "php");
    }

    #[test]
    fn leaves_an_existing_ide_helper_file_alone() {
        let host = MockHost::install().with_capabilities(&["project.read", "events", "process:tee"]);
        project(&host);
        host.add_file("_ide_helper.php", "<?php\n// laravel-ide-helper\n");
        let mut plugin = LaravelFacades::default();
        plugin.handle_events(&[Event::FileOpened("/p/routes/api.php".into())], &host.invocation());
        assert!(host.process_runs().is_empty());
    }

    #[test]
    fn a_missing_file_is_absent_in_both_error_forms() {
        assert!(is_missing(&Error::NotFound("_ide_helper.php".into())));
        assert!(is_missing(&Error::Invalid("_ide_helper.php: no such file".into())));
        assert!(is_missing(&Error::Invalid("_ide_helper.php: not found".into())));
        assert!(!is_missing(&Error::Invalid("_ide_helper.php: access outside the project root is not allowed".into())));
        assert!(!is_missing(&Error::Denied("project.read".into())));
    }

    #[test]
    fn ignores_projects_that_are_not_laravel() {
        let host = MockHost::install().with_capabilities(&["project.read", "events", "process:tee"]);
        host.set_project_root(Some("/p"));
        host.add_file("composer.json", r#"{"require":{"php":"^8.3"}}"#);
        let mut plugin = LaravelFacades::default();
        plugin.handle_events(&[Event::FileOpened("/p/index.php".into())], &host.invocation());
        assert!(host.process_runs().is_empty());
    }

    #[test]
    fn a_saved_composer_file_regenerates_the_stub() {
        let host = MockHost::install().with_capabilities(&["project.read", "events", "process:tee"]);
        project(&host);
        host.add_file("_ide_helper.php", "<?php\n// @generated by konakona.laravel-facades 0.0.1\nclass_alias(\\Old::class, 'Old');\n");
        let written = std::rc::Rc::new(std::cell::RefCell::new(None));
        tee(&host, written.clone());

        let mut plugin = LaravelFacades::default();
        plugin.handle_events(&[Event::FileSaved("/p/composer.lock".into())], &host.invocation());
        assert!(written.borrow().as_deref().is_some_and(|t| t.contains("'Route'")));
    }
}
